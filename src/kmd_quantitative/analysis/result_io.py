def artifacts():
    """Return fresh path/hash/schema records for the small result closure."""
    return deepcopy(_CATALOG)


def _read(key, root=None):
    record = _CATALOG[key]
    base = ROOT if root is None else Path(root)
    path = base / record['path']
    if not path.is_file():
        raise FileNotFoundError(f"Required saved artifact missing: {record['path']}; "
                                "restore this exact file using the release register")
    data = path.read_bytes()
    if len(data) != record['size_bytes'] or hashlib.sha256(data).hexdigest() != record['sha256']:
        raise ValueError(f"Saved artifact hash/size mismatch: {record['path']}")
    return record, data


def read_json(key, *, root=None):
    record, data = _read(key, root)
    if record['format'] != 'json':
        raise ValueError('Expected JSON artifact: ' + key)
    result = json.loads(data)
    if not isinstance(result, dict) or not set(record['required_keys']) <= result.keys():
        raise ValueError('JSON schema mismatch: ' + key)
    return result


def read_table(key, *, raw=False, root=None):
    """Read saved rows in original order; no filtering, filling or aggregation.

    raw=True returns list[dict[str, str]] without float conversion; the default
    returns pandas.DataFrame (empty fields become NaN for presentation only).
    """
    record, data = _read(key, root)
    if record['format'] != 'csv':
        raise ValueError('Expected CSV artifact: ' + key)
    reader = csv.DictReader(io.StringIO(data.decode('utf-8-sig')))
    rows = list(reader)
    if reader.fieldnames != record['columns'] or len(rows) != record['rows']:
        raise ValueError('CSV schema/row-count mismatch: ' + key)
    if any(None in row or any(v is None for v in row.values()) for row in rows):
        raise ValueError('Malformed CSV row: ' + key)
    if raw:
        return rows
    import pandas as pd
    return pd.read_csv(io.BytesIO(data))
